#!/usr/bin/env bash
# Injects a release signingConfig into the generated android/app/build.gradle.kts so that
# `flutter build appbundle --release` is signed with the key described by android/key.properties
# (keys: storePassword, keyPassword, keyAlias, storeFile; storeFile is relative to android/app/).
#
# Written against the Flutter stable app template (packages/flutter_tools/templates/app/android-kotlin.tmpl,
# fetched 2026-11-03), whose release build type contains:
#     signingConfig = signingConfigs.getByName("debug")
# Idempotent: running it twice changes nothing the second time. Fails loudly if the file does not look
# like the template, so a Flutter template change cannot silently produce a debug-signed release.
#
# Usage: patch_signing.sh [path/to/android]   (default: ../android relative to this script)
set -euo pipefail

ANDROID_DIR="${1:-$(cd "$(dirname "$0")/.." && pwd)/android}"
GRADLE="$ANDROID_DIR/app/build.gradle.kts"
MARK="looprun-release-signing"

if [ ! -f "$GRADLE" ]; then
  echo "patch_signing: $GRADLE not found (only the Kotlin DSL file generated by current Flutter is supported)" >&2
  exit 1
fi

if grep -q "$MARK" "$GRADLE"; then
  echo "patch_signing: already patched"
else
  for anchor in '^android \{' '^    buildTypes \{' 'signingConfig = signingConfigs.getByName\("debug"\)'; do
    if [ "$(grep -c -E "$anchor" "$GRADLE")" -ne 1 ]; then
      echo "patch_signing: expected exactly one match for /$anchor/ in $GRADLE; the Flutter template changed. Update this script." >&2
      exit 1
    fi
  done

  TMP="$(mktemp)"
  trap 'rm -f "$TMP"' EXIT
  awk -v mark="$MARK" '
    NR == 1 {
      print "// " mark ": imports (added by mobile/tool/patch_signing.sh)"
      print "import java.io.FileInputStream"
      print "import java.util.Properties"
      print ""
    }
    /^android \{/ {
      print "// " mark ": keystore properties (must come after the plugins block)"
      print "val keystoreProperties = Properties()"
      print "val keystorePropertiesFile = rootProject.file(\"key.properties\")"
      print "if (keystorePropertiesFile.exists()) {"
      print "    FileInputStream(keystorePropertiesFile).use { keystoreProperties.load(it) }"
      print "}"
      print ""
    }
    /^    buildTypes \{/ {
      print "    // " mark ": release signing config (added by mobile/tool/patch_signing.sh)"
      print "    signingConfigs {"
      print "        create(\"release\") {"
      print "            keyAlias = keystoreProperties.getProperty(\"keyAlias\")"
      print "            keyPassword = keystoreProperties.getProperty(\"keyPassword\")"
      print "            storeFile = keystoreProperties.getProperty(\"storeFile\")?.let { file(it) }"
      print "            storePassword = keystoreProperties.getProperty(\"storePassword\")"
      print "        }"
      print "    }"
      print ""
    }
    /signingConfig = signingConfigs.getByName\("debug"\)/ {
      sub(/getByName\("debug"\)/, "getByName(\"release\")")
    }
    { print }
  ' "$GRADLE" > "$TMP"
  cat "$TMP" > "$GRADLE"
  echo "patch_signing: patched $GRADLE"
fi

# Verify, whether we just patched or it was already patched.
grep -q "$MARK: release signing config" "$GRADLE" || { echo "patch_signing: signingConfigs block missing" >&2; exit 1; }
grep -q 'signingConfig = signingConfigs.getByName("release")' "$GRADLE" || { echo "patch_signing: release build type does not use the release signing config" >&2; exit 1; }
if grep -q 'signingConfigs.getByName("debug")' "$GRADLE"; then
  echo "patch_signing: debug signing still referenced in $GRADLE" >&2
  exit 1
fi
echo "patch_signing: verified"
